package com.devuloopers.knet.application.contract.traffic

/** Closed clipboard presets; presentation labels and menu grouping remain UI-owned. */
public enum class TrafficCopyPreset {
    /** Complete currently captured metadata and bounded payload evidence. */ FULL,
    /** Method, destination, status, byte count and timing without payload reads. */ SUMMARY,
    /** Exact recorded URL; opaque records disclose that no HTTP URL is available. */ URL,
    /** Canonical host and effective port, one selected record per line. */ DESTINATION,
    /** Recorded request path and raw query. */ PATH_QUERY,
    /** Decoded, ordered query name/value pairs. */ QUERY_PARAMETERS,
    /** Ordered request headers, including duplicates. */ REQUEST_HEADERS,
    /** Captured Cookie header values. */ REQUEST_COOKIES,
    /** Decoded and formatted request payload. */ REQUEST_BODY,
    /** Request headers and formatted payload. */ REQUEST_HEADERS_BODY,
    /** Captured request wire bytes encoded as Base64. */ REQUEST_BASE64,
    /** Captured request wire bytes encoded as hexadecimal. */ REQUEST_HEX,
    /** Ordered response headers, including duplicates. */ RESPONSE_HEADERS,
    /** Captured Set-Cookie header values. */ RESPONSE_COOKIES,
    /** Decoded and formatted response payload. */ RESPONSE_BODY,
    /** Decoded response text before JSON prettification. */ RESPONSE_ORIGINAL_TEXT,
    /** Response headers and formatted payload. */ RESPONSE_HEADERS_BODY,
    /** Captured response wire bytes encoded as Base64. */ RESPONSE_BASE64,
    /** Captured response wire bytes encoded as hexadecimal. */ RESPONSE_HEX,
    /** URL and formatted request payload. */ URL_REQUEST_BODY,
    /** URL, request headers and formatted payload. */ URL_REQUEST_HEADERS_BODY,
    /** URL, observed response status and formatted payload. */ URL_RESPONSE_BODY,
    /** URL, observed response status, headers and formatted payload. */ URL_RESPONSE_HEADERS_BODY,
    /** Formatted request and response payloads. */ REQUEST_RESPONSE_BODIES,
    /** Both directions' headers and formatted payloads. */ REQUEST_RESPONSE_HEADERS_BODIES,
    /** GraphQL query document, including known persisted-query resolution provenance. */ GRAPHQL_QUERY,
    /** GraphQL variables JSON. */ GRAPHQL_VARIABLES,
    /** GraphQL extension JSON. */ GRAPHQL_EXTENSIONS,
    /** GraphQL operation type, name and query provenance. */ GRAPHQL_OPERATION,
    /** Complete semantic HTTP GraphQL request. */ GRAPHQL_REQUEST,
    /** Bounded captured WebSocket messages in both directions. */ WEBSOCKET_MESSAGES,
    /** Bounded captured client WebSocket messages. */ WEBSOCKET_CLIENT_MESSAGES,
    /** Bounded captured server WebSocket messages. */ WEBSOCKET_SERVER_MESSAGES,
    /** WebSocket request/response handshake headers. */ WEBSOCKET_HANDSHAKE,
    /** Recorded gRPC service and method. */ GRPC_METHOD,
    /** Captured gRPC request/response metadata and trailers. */ GRPC_METADATA,
    /** Bounded captured gRPC messages. */ GRPC_MESSAGES,
    /** Bounded captured SSE event records. */ SSE_EVENTS,
    /** Data fields from bounded captured SSE records. */ SSE_DATA,
    /** Observed transport, protocol and TLS metadata. */ CONNECTION,
    /** Recorded timing measurements; absent timings remain explicit. */ TIMINGS,
    /** Recorded failure, rejection and closure evidence. */ FAILURE_CLOSURE,
    /** Shell-quoted cURL for compatible, fully retained HTTP requests; never executes it. */ CURL,
    /** Structured, versioned JSON containing each selected record and its available evidence. */ STRUCTURED_JSON,
}
