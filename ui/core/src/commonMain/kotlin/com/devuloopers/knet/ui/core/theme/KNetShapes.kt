package com.devuloopers.knet.ui.core.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

/**
 * Standardized corner radius shapes for KNet UI components.
 */
public object KNetShapes {
    public val Small: RoundedCornerShape = RoundedCornerShape(4.dp)
    public val Medium: RoundedCornerShape = RoundedCornerShape(6.dp)
    public val Large: RoundedCornerShape = RoundedCornerShape(8.dp)
    public val Pill: RoundedCornerShape = RoundedCornerShape(50)
}
